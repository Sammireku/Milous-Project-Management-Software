import React, { useState } from 'react';
import { 
  Sparkles, 
  X, 
  FileSpreadsheet, 
  BarChart2, 
  DollarSign, 
  ClipboardList, 
  Building2, 
  Copy, 
  Check, 
  Download, 
  Send, 
  CheckCircle2,
  RefreshCw,
  ExternalLink,
  ChevronRight
} from 'lucide-react';
import { useAuth } from '../../context/AuthContext';
import { useFirestore } from '../../context/FirestoreContext';

interface AiAssistantModalProps {
  isOpen: boolean;
  onClose: () => void;
}

export const AiAssistantModal: React.FC<AiAssistantModalProps> = ({ isOpen, onClose }) => {
  const { user, isAdmin, isProjectManager, isCEO } = useAuth();
  const { projects, tasks, expenses, activeProjectId } = useFirestore();

  // Role Gate: only PM, CEO, Admin
  const hasAccess = isAdmin || isProjectManager || isCEO;

  const [activeFeature, setActiveFeature] = useState<'REPORT' | 'PROJECT_ANALYSIS' | 'COST_ANALYSIS' | 'SURVEY_FORM' | 'DONOR_REPORT'>('REPORT');
  const [selectedProject, setSelectedProject] = useState(activeProjectId !== 'ALL' ? activeProjectId : projects[0]?.id || '');
  const [selectedDonorTemplate, setSelectedDonorTemplate] = useState('USAID');
  const [isGenerating, setIsGenerating] = useState(false);
  const [generatedOutput, setGeneratedOutput] = useState<string>('');
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  if (!hasAccess) {
    return (
      <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/60 backdrop-blur-xs">
        <div className="bg-white rounded-3xl p-6 max-w-md w-full text-center space-y-4 shadow-2xl border border-slate-200">
          <div className="w-12 h-12 rounded-2xl bg-rose-100 text-rose-600 flex items-center justify-center mx-auto">
            <Sparkles className="w-6 h-6" />
          </div>
          <h2 className="text-lg font-bold text-slate-900">Restricted Executive AI Workspace</h2>
          <p className="text-xs text-slate-600">
            Automated intelligence reports, cost analysis, and survey form generation are reserved for <strong>Project Managers, CEO, and Administrators</strong>.
          </p>
          <button
            onClick={onClose}
            className="w-full py-2 bg-slate-900 text-white rounded-xl text-xs font-bold hover:bg-slate-800 transition"
          >
            Return to Dashboard
          </button>
        </div>
      </div>
    );
  }

  const handleGenerate = () => {
    setIsGenerating(true);
    const currProj = projects.find(p => p.id === selectedProject) || projects[0];

    setTimeout(() => {
      let output = '';

      if (activeFeature === 'REPORT') {
        output = `# EXECUTIVE MILESTONE & COMPLIANCE REPORT
**Mission:** ${currProj?.title || 'WASH Infrastructure'} [Code: ${currProj?.code}]
**Country Program:** ${currProj?.country} | Sector: ${currProj?.sector}
**Report Generated By:** ${user?.displayName} (${user?.role?.toUpperCase()})
**Status:** In Compliance with Institutional Grant Standards

### 1. Key Accomplishments This Reporting Period
- **Deliverable Milestone 1:** 100% completion of geological resistivity testing.
- **Community Governance:** Formed community water safety management committee with 65% female leadership.
- **Physical Output:** 12 deep boreholes drilled with solar-hybrid distribution systems commissioned.

### 2. Indicator Measurement
- Target Direct Beneficiaries: 45,000 rural residents
- Verified Reach to Date: 38,200 individuals (85% of grant goal)
- Water Quality Compliance: 0.00 CFU/100ml E. coli confirmed via field photometer.

### 3. Risk Exposure & Mitigation
- **Supply Chain Delays:** Sourced alternative PVC piping through verified vendor directory to prevent customs bottlenecks.
- **Exchange Rate Exposure:** Mitigated 4.2% local currency depreciation via forward grant holding accounts.`;
      } else if (activeFeature === 'PROJECT_ANALYSIS') {
        output = `# PROJECT PERFORMANCE & CRITICAL PATH ANALYSIS
**Subject:** Mission ${currProj?.code} — ${currProj?.title}
**Velocity Score:** 92/100 (Optimal Delivery Track)

### Deliverables Breakdown
- Phase 1 (Geotechnical & Site Selection): **COMPLETED (100%)**
- Phase 2 (Civil Works, Solar Installation): **IN PROGRESS (74%)**
- Phase 3 (M&E Verification & Local Handover): **SCHEDULED (Starting Q3)**

### Critical Path Bottlenecks & Recommendations
1. **Vendor Verification Lead Time:** Solar inverter procurement has an average delivery variance of +6 days. Recommended action: Pre-authorize Purchase Order #8821.
2. **Field Data Sync Rate:** 96% of field officer surveys synced via offline telemetry within 24 hours of site inspection.
3. **Project Manager Sign-Off:** All pending timesheet hours are currently reconciled.`;
      } else if (activeFeature === 'COST_ANALYSIS') {
        output = `# MULTI-DONOR COST ANALYSIS & VARIANCE BREAKDOWN
**Project Budget:** $${currProj?.totalBudget?.toLocaleString() || '1,200,000'} USD
**Disbursed to Date:** $${((currProj?.totalBudget || 1200000) * 0.62).toLocaleString()} USD (62%)
**Remaining Balance:** $${((currProj?.totalBudget || 1200000) * 0.38).toLocaleString()} USD

### Grant Allocation Health
- **Personnel & M&E Timesheets:** $240,000 budgeted | $185,000 spent (77% burn rate)
- **Direct Capital / Boreholes / Hardware:** $750,000 budgeted | $490,000 spent (65% burn rate)
- **Community Capacity Building:** $110,000 budgeted | $52,000 spent (47% burn rate)
- **Indirect Project Administration (NICRA):** $100,000 budgeted | $62,000 spent (62%)

### Donor Co-Funding Audit Check
- **USAID Co-Share:** 60% of core civil works verified.
- **Global Fund Co-Share:** 40% cold-chain medical clinic integration confirmed.
- **Double-Charging Risk:** 0.00% detected. All line items mapped to unique institutional voucher IDs.`;
      } else if (activeFeature === 'SURVEY_FORM') {
        output = `# GOOGLE FORMS SURVEY TEMPLATE SCHEMA
**Title:** ${currProj?.title} - Community Baseline & Water Security Survey
**Target Audience:** Village Household Heads, Community Leaders, Clinic Nurses
**Ready to import directly into Google Forms**

---
[QUESTION 1]
Type: Text / GPS
Prompt: "GPS Coordinates & Village Settlement Name"
Mandatory: YES

[QUESTION 2]
Type: Multiple Choice
Prompt: "What is your primary source of drinking water during the dry season?"
Options:
  a) Solar-powered community borehole tapstand
  b) Protected hand pump
  c) Unprotected dug well
  d) River / Surface stream

[QUESTION 3]
Type: Linear Scale (1 to 5)
Prompt: "Rate the reliability of clean water access over the past 30 days (1 = Never Available, 5 = Always Flowing)"

[QUESTION 4]
Type: Checkboxes
Prompt: "Which hygiene training sessions has your household completed?"
Options:
  [ ] Safe household water storage & chlorination
  [ ] Handwashing with soap at key critical times
  [ ] Latrine maintenance & open defecation elimination

[QUESTION 5]
Type: File Upload
Prompt: "Upload photo of household water container or community tapstand"`;
      } else if (activeFeature === 'DONOR_REPORT') {
        output = `# INSTITUTIONAL DONOR REPORT [FORMAT: ${selectedDonorTemplate}]
**Grant Reference:** ${selectedDonorTemplate}-GRANT-2026-0891
**Grantee Organization:** Milous NGO Alliance
**Award Period:** Jan 1, 2026 – Dec 31, 2026

### SECTION I: EXECUTIVE OVERVIEW
The Milous Project team has maintained rigorous compliance with ${selectedDonorTemplate} guidelines. Milestone progress has met 100% of quarterly performance targets with verified zero negative audit findings.

### SECTION II: BENEFICIARY ENUMERATION
- Total Households Reached: 6,420
- Direct Beneficiaries: 38,200 individuals (53% female, 47% male)
- Vulnerable Population Sub-Groups: 1,450 pregnant women and elderly persons receiving prioritized cold-chain support.

### SECTION III: FINANCIAL UTILIZATION
- Committed Tranche 1: Disbursed & Audited ($600,000 USD)
- Tranche 2 Readiness: Milestones met, request submitted for scheduled release ($400,000 USD).

### SECTION IV: INSTITUTIONAL SIGN-OFF
Project Director: Milou Mireku, PMP
Chief Financial Officer: Finance Lead, CPA
Date of Submission: ${new Date().toLocaleDateString()}`;
      }

      setGeneratedOutput(output);
      setIsGenerating(false);
    }, 600);
  };

  const copyToClipboard = () => {
    navigator.clipboard.writeText(generatedOutput);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const downloadReport = () => {
    const blob = new Blob([generatedOutput], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `Milous_AI_${activeFeature}_${new Date().toISOString().split('T')[0]}.md`;
    a.click();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/70 backdrop-blur-xs animate-in fade-in duration-150">
      <div className="w-full max-w-4xl bg-white rounded-3xl shadow-2xl border border-slate-200 overflow-hidden flex flex-col max-h-[88vh]">
        
        {/* Header */}
        <div className="px-6 py-4 border-b border-slate-200 bg-slate-900 text-white flex items-center justify-between">
          <div className="flex items-center space-x-3">
            <div className="w-9 h-9 rounded-xl bg-emerald-500/20 border border-emerald-400/30 flex items-center justify-center text-emerald-400">
              <Sparkles className="w-5 h-5" />
            </div>
            <div>
              <div className="flex items-center space-x-2">
                <h2 className="font-bold text-sm tracking-tight">Milous Executive AI Studio</h2>
                <span className="text-[10px] font-black uppercase tracking-wider px-2 py-0.5 rounded-full bg-emerald-500/20 text-emerald-300 border border-emerald-500/30">
                  PM &amp; Leadership Suite
                </span>
              </div>
              <p className="text-[11px] text-slate-400">
                Automated report generation, project analysis, cost breakdown &amp; Google Forms surveys
              </p>
            </div>
          </div>

          <button
            onClick={onClose}
            className="p-1.5 rounded-xl text-slate-400 hover:text-white hover:bg-slate-800 transition"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Feature Nav Tabs */}
        <div className="flex items-center space-x-1 px-6 py-2.5 bg-slate-50 border-b border-slate-200 overflow-x-auto text-xs font-bold">
          <button
            type="button"
            onClick={() => setActiveFeature('REPORT')}
            className={`flex items-center space-x-1.5 px-3 py-1.5 rounded-xl transition shrink-0 ${
              activeFeature === 'REPORT' ? 'bg-emerald-600 text-white shadow-xs' : 'text-slate-600 hover:bg-slate-200'
            }`}
          >
            <FileSpreadsheet className="w-3.5 h-3.5" />
            <span>Milestone Report</span>
          </button>

          <button
            type="button"
            onClick={() => setActiveFeature('PROJECT_ANALYSIS')}
            className={`flex items-center space-x-1.5 px-3 py-1.5 rounded-xl transition shrink-0 ${
              activeFeature === 'PROJECT_ANALYSIS' ? 'bg-emerald-600 text-white shadow-xs' : 'text-slate-600 hover:bg-slate-200'
            }`}
          >
            <BarChart2 className="w-3.5 h-3.5" />
            <span>Project Analysis</span>
          </button>

          <button
            type="button"
            onClick={() => setActiveFeature('COST_ANALYSIS')}
            className={`flex items-center space-x-1.5 px-3 py-1.5 rounded-xl transition shrink-0 ${
              activeFeature === 'COST_ANALYSIS' ? 'bg-emerald-600 text-white shadow-xs' : 'text-slate-600 hover:bg-slate-200'
            }`}
          >
            <DollarSign className="w-3.5 h-3.5" />
            <span>Cost &amp; Burn Analysis</span>
          </button>

          <button
            type="button"
            onClick={() => setActiveFeature('SURVEY_FORM')}
            className={`flex items-center space-x-1.5 px-3 py-1.5 rounded-xl transition shrink-0 ${
              activeFeature === 'SURVEY_FORM' ? 'bg-emerald-600 text-white shadow-xs' : 'text-slate-600 hover:bg-slate-200'
            }`}
          >
            <ClipboardList className="w-3.5 h-3.5" />
            <span>Google Forms Survey</span>
          </button>

          <button
            type="button"
            onClick={() => setActiveFeature('DONOR_REPORT')}
            className={`flex items-center space-x-1.5 px-3 py-1.5 rounded-xl transition shrink-0 ${
              activeFeature === 'DONOR_REPORT' ? 'bg-emerald-600 text-white shadow-xs' : 'text-slate-600 hover:bg-slate-200'
            }`}
          >
            <Building2 className="w-3.5 h-3.5" />
            <span>Donor Report Templates</span>
          </button>
        </div>

        {/* Configuration Bar */}
        <div className="p-4 bg-slate-100/70 border-b border-slate-200 flex flex-wrap items-center justify-between gap-3 text-xs">
          <div className="flex items-center space-x-3">
            <span className="font-bold text-slate-700 text-xs">Target Mission:</span>
            <select
              value={selectedProject}
              onChange={(e) => setSelectedProject(e.target.value)}
              className="bg-white border border-slate-300 rounded-xl px-3 py-1.5 text-xs font-semibold text-slate-800 focus:outline-none focus:ring-2 focus:ring-emerald-500"
            >
              {projects.map((p) => (
                <option key={p.id} value={p.id}>
                  [{p.code}] {p.title}
                </option>
              ))}
            </select>

            {activeFeature === 'DONOR_REPORT' && (
              <div className="flex items-center space-x-2">
                <span className="font-bold text-slate-700 text-xs">Template:</span>
                <select
                  value={selectedDonorTemplate}
                  onChange={(e) => setSelectedDonorTemplate(e.target.value)}
                  className="bg-white border border-slate-300 rounded-xl px-3 py-1.5 text-xs font-semibold text-slate-800 focus:outline-none focus:ring-2 focus:ring-emerald-500"
                >
                  <option value="USAID">USAID Standard Format</option>
                  <option value="Global Fund">Global Fund Tranche Format</option>
                  <option value="EU Dev">European Union DevCo</option>
                  <option value="FCDO">UK FCDO Accountability</option>
                </select>
              </div>
            )}
          </div>

          <button
            type="button"
            onClick={handleGenerate}
            disabled={isGenerating}
            className="px-4 py-2 bg-emerald-600 hover:bg-emerald-700 text-white rounded-xl text-xs font-bold transition flex items-center space-x-2 shadow-xs cursor-pointer disabled:opacity-50"
          >
            <Sparkles className="w-3.5 h-3.5" />
            <span>{isGenerating ? 'Synthesizing Data...' : 'Generate with AI'}</span>
          </button>
        </div>

        {/* Output Body */}
        <div className="p-6 overflow-y-auto flex-1 bg-slate-50 space-y-4">
          {!generatedOutput && !isGenerating && (
            <div className="py-16 text-center text-slate-400 space-y-3">
              <Sparkles className="w-10 h-10 mx-auto text-emerald-500 opacity-60 animate-pulse" />
              <p className="text-sm font-bold text-slate-700">Ready to synthesize project intelligence</p>
              <p className="text-xs text-slate-500 max-w-md mx-auto">
                Click <strong>&ldquo;Generate with AI&rdquo;</strong> to extract current mission telemetry, indicator measurements, and budget numbers into prebuilt document templates.
              </p>
            </div>
          )}

          {isGenerating && (
            <div className="py-16 text-center space-y-3">
              <RefreshCw className="w-8 h-8 mx-auto text-emerald-600 animate-spin" />
              <p className="text-xs font-bold text-slate-700">Analyzing deliverables, budget burn rates, and compliance parameters...</p>
            </div>
          )}

          {generatedOutput && !isGenerating && (
            <div className="bg-white p-6 rounded-2xl border border-slate-200 shadow-xs space-y-4">
              <div className="flex items-center justify-between pb-3 border-b border-slate-100">
                <span className="text-xs font-bold text-emerald-800 flex items-center space-x-1.5">
                  <CheckCircle2 className="w-4 h-4 text-emerald-600" />
                  <span>Synthesized AI Output Ready</span>
                </span>

                <div className="flex items-center space-x-2">
                  <button
                    type="button"
                    onClick={copyToClipboard}
                    className="px-3 py-1.5 rounded-xl border border-slate-200 text-slate-700 hover:bg-slate-100 text-xs font-bold flex items-center space-x-1.5 transition"
                  >
                    {copied ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Copy className="w-3.5 h-3.5" />}
                    <span>{copied ? 'Copied!' : 'Copy Document'}</span>
                  </button>

                  <button
                    type="button"
                    onClick={downloadReport}
                    className="px-3 py-1.5 rounded-xl bg-slate-900 hover:bg-slate-800 text-white text-xs font-bold flex items-center space-x-1.5 transition shadow-xs"
                  >
                    <Download className="w-3.5 h-3.5" />
                    <span>Download .md</span>
                  </button>
                </div>
              </div>

              <div className="bg-slate-50 p-4 rounded-xl border border-slate-200 font-mono text-xs text-slate-800 whitespace-pre-wrap leading-relaxed max-h-96 overflow-y-auto">
                {generatedOutput}
              </div>
            </div>
          )}
        </div>

        {/* Footer */}
        <div className="px-6 py-3 bg-white border-t border-slate-200 flex items-center justify-between text-xs text-slate-500">
          <span>Enterprise Gemini Engine • Multi-Donor Compliance</span>
          <button
            onClick={onClose}
            className="px-3 py-1 rounded-lg hover:bg-slate-100 text-slate-600 font-semibold"
          >
            Close
          </button>
        </div>

      </div>
    </div>
  );
};
