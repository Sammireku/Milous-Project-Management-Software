import React, { useState } from 'react';
import { 
  Sparkles, 
  Zap, 
  Bot, 
  CheckCircle2, 
  Code2, 
  Copy, 
  SlidersHorizontal, 
  ShieldAlert, 
  Terminal, 
  RefreshCw,
  Send,
  Sliders,
  Check,
  Flame,
  FileCode2,
  Server
} from 'lucide-react';
import { useFirestore } from '../../context/FirestoreContext';
import { useAuth } from '../../context/AuthContext';

export interface GeneratedFirebaseAutomation {
  id: string;
  commandPrompt: string;
  firestoreRule: string;
  cloudFunctionTrigger: string;
  createdAt: string;
  deployed: boolean;
}

export const WrikeAiAutomationView: React.FC = () => {
  const { tasks } = useFirestore();
  const { currentUser } = useAuth();

  // Natural Language Command Input
  const [nlPrompt, setNlPrompt] = useState('If an expense is over $1000, alert the finance manager');
  const [isAiGenerating, setIsAiGenerating] = useState(false);
  const [copiedType, setCopiedType] = useState<string | null>(null);
  const [deployStatus, setDeployStatus] = useState<string | null>(null);

  // Generated Automation Code State
  const [generatedAutomation, setGeneratedAutomation] = useState<GeneratedFirebaseAutomation>({
    id: 'auto-gen-01',
    commandPrompt: 'If an expense is over $1000, alert the finance manager',
    firestoreRule: `// Firestore Security Rule (generated by AI Studio Agent)
match /expenses/{expenseId} {
  allow create, update: if request.resource.data.amount <= 1000 
    || request.auth.token.role == 'finance_manager'
    || request.auth.token.role == 'ADMIN';
  allow read: if request.auth != null;
}`,
    cloudFunctionTrigger: `// Firebase Cloud Function Trigger (generated by AI Studio Agent)
import * as functions from 'firebase-functions';
import * as admin from 'firebase-admin';

export const onExpenseCreated = functions.firestore
  .document('expenses/{expenseId}')
  .onCreate(async (snap, context) => {
    const expense = snap.data();
    if (expense.amount > 1000) {
      console.log(\`High-value expense flagged: \${expense.id} ($ \${expense.amount})\`);
      
      // Dispatch alert to Finance Manager
      await admin.firestore().collection('notifications').add({
        targetRole: 'finance_manager',
        title: 'High Expense Alert',
        message: \`Expense "\${expense.description}" ($ \${expense.amount}) requires mandatory financial review.\`,
        createdAt: admin.firestore.FieldValue.serverTimestamp(),
        expenseId: context.params.expenseId,
      });
    }
  });`,
    createdAt: new Date().toISOString(),
    deployed: true,
  });

  const handleSynthesizeCommand = () => {
    if (!nlPrompt.trim()) return;
    setIsAiGenerating(true);

    setTimeout(() => {
      const lower = nlPrompt.toLowerCase();

      let collectionName = 'expenses';
      let threshold = 1000;
      const amountMatch = nlPrompt.match(/\$?(\d+)/);
      if (amountMatch) {
        threshold = parseInt(amountMatch[1], 10);
      }

      if (lower.includes('task') || lower.includes('subtask')) collectionName = 'tasks';
      else if (lower.includes('incident') || lower.includes('risk')) collectionName = 'incidents';
      else if (lower.includes('requisition')) collectionName = 'requisitions';

      const ruleCode = `// Firestore Security Rule
match /${collectionName}/{docId} {
  allow create, update: if request.resource.data.amount <= ${threshold} 
    || request.auth.token.role == 'finance_manager'
    || request.auth.token.role == 'ADMIN';
  allow read: if request.auth != null;
}`;

      const functionCode = `// Firebase Cloud Function Trigger
import * as functions from 'firebase-functions';
import * as admin from 'firebase-admin';

export const on${collectionName.charAt(0).toUpperCase() + collectionName.slice(1)}Created = functions.firestore
  .document('${collectionName}/{docId}')
  .onCreate(async (snap, context) => {
    const data = snap.data();
    if (data.amount > ${threshold} || data.priority === 'URGENT') {
      console.log(\`Trigger condition met for prompt: "${nlPrompt}"\`);
      
      await admin.firestore().collection('notifications').add({
        targetRole: 'finance_manager',
        title: 'Automated AI Workflow Alert',
        message: \`Condition triggered: \${data.title || data.description || 'Record'} ($ \${data.amount || 0}).\`,
        createdAt: admin.firestore.FieldValue.serverTimestamp(),
        docId: context.params.docId,
      });
    }
  });`;

      setGeneratedAutomation({
        id: `auto-gen-${Date.now()}`,
        commandPrompt: nlPrompt,
        firestoreRule: ruleCode,
        cloudFunctionTrigger: functionCode,
        createdAt: new Date().toISOString(),
        deployed: false,
      });

      setIsAiGenerating(false);
      setDeployStatus(null);
    }, 1000);
  };

  const handleCopyCode = (text: string, type: string) => {
    navigator.clipboard.writeText(text);
    setCopiedType(type);
    setTimeout(() => setCopiedType(null), 2500);
  };

  const handleSimulateDeploy = () => {
    setDeployStatus('deploying');
    setTimeout(() => {
      setGeneratedAutomation((prev) => ({ ...prev, deployed: true }));
      setDeployStatus('deployed');
    }, 1500);
  };

  return (
    <div className="space-y-6">
      {/* AI Automation Natural Language Header */}
      <div className="bg-gradient-to-r from-slate-900 via-indigo-950 to-slate-900 rounded-2xl border border-indigo-900/60 p-6 text-white shadow-lg space-y-4">
        <div className="flex items-center space-x-3">
          <div className="w-10 h-10 rounded-2xl bg-indigo-500 text-white flex items-center justify-center font-black shadow-md">
            <Bot className="w-6 h-6 text-indigo-100" />
          </div>
          <div>
            <h3 className="text-base font-extrabold text-white flex items-center space-x-2">
              <span>Wrike AI Automation Assistant</span>
              <span className="bg-indigo-500/30 text-indigo-300 font-mono text-[10px] px-2 py-0.5 rounded-full border border-indigo-400/30 font-bold">
                Firebase Rule &amp; Function Generator
              </span>
            </h3>
            <p className="text-xs text-indigo-200 mt-0.5">
              Type plain-text rules (e.g. "If an expense is over $1000, alert the finance manager"). AI converts it into Firestore rules &amp; Cloud Function triggers.
            </p>
          </div>
        </div>

        {/* Command Input Bar */}
        <div className="flex flex-col sm:flex-row items-center gap-2 pt-2">
          <div className="relative flex-1 w-full">
            <input
              type="text"
              value={nlPrompt}
              onChange={(e) => setNlPrompt(e.target.value)}
              placeholder="e.g., If an expense is over $1000, alert the finance manager..."
              className="w-full bg-slate-800/90 border border-indigo-700/60 text-white placeholder-slate-400 text-xs rounded-xl px-4 py-3 focus:outline-none focus:ring-2 focus:ring-indigo-400/40 font-medium"
            />
            <Sparkles className="w-4 h-4 text-indigo-400 absolute right-3 top-3.5" />
          </div>

          <button
            type="button"
            onClick={handleSynthesizeCommand}
            disabled={isAiGenerating || !nlPrompt.trim()}
            className="w-full sm:w-auto px-5 py-3 rounded-xl bg-emerald-500 hover:bg-emerald-400 disabled:opacity-50 text-slate-950 font-black text-xs flex items-center justify-center space-x-2 transition shadow-md shrink-0"
          >
            {isAiGenerating ? (
              <>
                <RefreshCw className="w-4 h-4 animate-spin text-slate-950" />
                <span>Generating Firebase Code...</span>
              </>
            ) : (
              <>
                <Zap className="w-4 h-4 fill-slate-950" />
                <span>Generate Rule &amp; Function</span>
              </>
            )}
          </button>
        </div>

        {/* Preset Example Prompts */}
        <div className="flex flex-wrap items-center gap-2 text-[11px] pt-1">
          <span className="text-indigo-300 font-bold">Sample Commands:</span>
          {[
            'If an expense is over $1000, alert the finance manager',
            'If a task is marked URGENT, trigger emergency SMS dispatch',
            'If field verification is completed, increment M&E indicator target',
          ].map((promptText, idx) => (
            <button
              key={idx}
              type="button"
              onClick={() => setNlPrompt(promptText)}
              className="bg-indigo-900/40 hover:bg-indigo-800/60 text-indigo-200 border border-indigo-700/50 px-2.5 py-1 rounded-lg text-[10px] font-semibold transition"
            >
              "{promptText}"
            </button>
          ))}
        </div>
      </div>

      {/* Generated Code Output Panels */}
      <div className="grid grid-cols-1 lg:grid-cols-2 gap-6">
        
        {/* Firestore Security Rule Code Box */}
        <div className="bg-slate-950 rounded-2xl border border-slate-800 p-5 space-y-3 text-white flex flex-col justify-between shadow-md">
          <div className="space-y-3">
            <div className="flex items-center justify-between pb-2 border-b border-slate-800">
              <div className="flex items-center space-x-2">
                <Flame className="w-4 h-4 text-amber-500" />
                <h4 className="text-xs font-bold text-white font-mono">firestore.rules Snippet</h4>
              </div>

              <button
                type="button"
                onClick={() => handleCopyCode(generatedAutomation.firestoreRule, 'rule')}
                className="text-[10px] font-bold px-2.5 py-1 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-200 flex items-center space-x-1.5 transition border border-slate-700"
              >
                {copiedType === 'rule' ? <Check className="w-3 h-3 text-emerald-400" /> : <Copy className="w-3 h-3" />}
                <span>{copiedType === 'rule' ? 'Copied Rule!' : 'Copy Rule'}</span>
              </button>
            </div>

            <pre className="p-4 rounded-xl bg-slate-900/90 text-emerald-400 font-mono text-[11px] leading-relaxed overflow-x-auto border border-slate-800/80">
              <code>{generatedAutomation.firestoreRule}</code>
            </pre>
          </div>

          <div className="pt-2 text-[10px] text-slate-400 font-mono flex justify-between items-center">
            <span>Enforces client-side authorization &amp; data validation</span>
            <span className="text-emerald-500 font-bold">Valid Syntax</span>
          </div>
        </div>

        {/* Firebase Cloud Function Trigger Code Box */}
        <div className="bg-slate-950 rounded-2xl border border-slate-800 p-5 space-y-3 text-white flex flex-col justify-between shadow-md">
          <div className="space-y-3">
            <div className="flex items-center justify-between pb-2 border-b border-slate-800">
              <div className="flex items-center space-x-2">
                <Server className="w-4 h-4 text-indigo-400" />
                <h4 className="text-xs font-bold text-white font-mono">functions/index.ts Trigger</h4>
              </div>

              <button
                type="button"
                onClick={() => handleCopyCode(generatedAutomation.cloudFunctionTrigger, 'function')}
                className="text-[10px] font-bold px-2.5 py-1 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-200 flex items-center space-x-1.5 transition border border-slate-700"
              >
                {copiedType === 'function' ? <Check className="w-3 h-3 text-emerald-400" /> : <Copy className="w-3 h-3" />}
                <span>{copiedType === 'function' ? 'Copied Function!' : 'Copy Function'}</span>
              </button>
            </div>

            <pre className="p-4 rounded-xl bg-slate-900/90 text-indigo-300 font-mono text-[11px] leading-relaxed overflow-x-auto border border-slate-800/80">
              <code>{generatedAutomation.cloudFunctionTrigger}</code>
            </pre>
          </div>

          <div className="pt-2 text-[10px] text-slate-400 font-mono flex justify-between items-center">
            <span>Serverless event handler triggered on document creation</span>
            <span className="text-indigo-400 font-bold">Node.js 20 ESM</span>
          </div>
        </div>
      </div>

      {/* Deployment Simulation Toolbar */}
      <div className="p-4 rounded-2xl bg-white border border-slate-200/80 flex flex-col sm:flex-row items-center justify-between gap-3 shadow-xs">
        <div className="flex items-center space-x-3">
          <div className="w-8 h-8 rounded-xl bg-emerald-100 text-emerald-800 flex items-center justify-center font-bold">
            <CheckCircle2 className="w-5 h-5 text-emerald-600" />
          </div>
          <div>
            <h4 className="text-xs font-extrabold text-slate-900">
              Active Command: "{generatedAutomation.commandPrompt}"
            </h4>
            <p className="text-[11px] text-slate-500">
              Synthesized and compiled for Firebase Firestore &amp; Cloud Functions environment.
            </p>
          </div>
        </div>

        <button
          type="button"
          onClick={handleSimulateDeploy}
          disabled={deployStatus === 'deploying'}
          className="px-5 py-2.5 rounded-xl bg-slate-900 hover:bg-slate-800 text-white font-bold text-xs flex items-center space-x-2 transition shadow-xs"
        >
          {deployStatus === 'deploying' ? (
            <>
              <RefreshCw className="w-4 h-4 animate-spin text-emerald-400" />
              <span>Deploying to Firebase...</span>
            </>
          ) : generatedAutomation.deployed ? (
            <>
              <Check className="w-4 h-4 text-emerald-400" />
              <span>Deployed to Firebase Project</span>
            </>
          ) : (
            <>
              <Flame className="w-4 h-4 text-amber-400 fill-amber-400" />
              <span>Simulate Firebase Deploy</span>
            </>
          )}
        </button>
      </div>
    </div>
  );
};

export default WrikeAiAutomationView;
